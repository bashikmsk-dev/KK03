#!/usr/bin/env bash
#
# Иконки сайта «Кибер Кино» из портрета со страницы 404.
#
# Исходник прозрачный, поэтому кладём его на фирменный тёмный фон: иконка
# одинаково читается и в светлой, и в тёмной теме браузера. Кадр взят по лицу —
# целиком портрет в 16 пикселей не умещается, узнаваемы только причёска и язык.
# Лёгкий подъём яркости и контраста нужен ровно для маленьких размеров: без
# него лицо в крошечной иконке сливается в серое пятно.
#
# Запуск:  bash tools/make_favicon.sh
# Нужен ImageMagick (команда convert).

set -euo pipefail
cd "$(dirname "$0")/.."

SRC=assets/img/enshtane-404.png
OUT=public
CROP=520x520+410+45

# один и тот же вид для всех размеров, иначе иконки не похожи друг на друга
look=(-background '#08080A' -alpha remove -alpha off -modulate 108 -sigmoidal-contrast 3,45%)

icon() { # icon <размер> <файл> [доп. параметры]
  convert "$SRC" -crop "$CROP" +repage "${look[@]}" \
    -filter Lanczos -resize "$1x$1" -strip "${@:3}" "$2"
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# favicon.ico — вкладка браузера и выдача поисковиков. Три размера в одном
# файле: систему и браузер мы не выбираем, пусть берут подходящий.
# Резкость добавляем только здесь: уменьшение фотографии до пары десятков
# пикселей всегда даёт мыло, и без подчёркнутых краёв лицо в него и
# превращается. Крупным иконкам это не нужно.
for size in 16 32 48; do icon "$size" "$tmp/$size.png" -unsharp 0x0.7+1.1+0.02; done
convert "$tmp/16.png" "$tmp/32.png" "$tmp/48.png" "$OUT/favicon.ico"

# 256 цветов вместо полноцветного PNG: портрет почти чёрно-белый, на глаз
# разницы нет, а файл втрое легче.
icon 180 "$OUT/apple-touch-icon.png" -colors 256 # «на экран Домой» в iOS
icon 192 "$OUT/icon-192.png" -colors 256         # Android и панели вебмастеров

echo "Готово:"
ls -la "$OUT/favicon.ico" "$OUT/apple-touch-icon.png" "$OUT/icon-192.png"
